import { chromium } from "playwright";
const out = process.argv[2];
const browser = await chromium.launch({ executablePath: process.env.PW_CHROMIUM_PATH, args: ["--use-gl=swiftshader", "--enable-webgl", "--ignore-gpu-blocklist"] });
const logs = [];
const page = await browser.newPage({ viewport: { width: 1600, height: 950 } });
page.on("pageerror", (e) => logs.push("pageerror: " + e.message));
page.on("console", (m) => m.type() === "error" && logs.push("console: " + m.text()));
await page.goto("http://localhost:5180/");
await page.waitForTimeout(5000);
await page.click('[data-tab="ionic"]');
await page.click('[data-testid="ionic-run"]');
await page.waitForTimeout(9000);
await page.screenshot({ path: `${out}/ionic.png` });
await page.click('[data-tab="scenarios"]');
await page.click('[data-scenario="pvc"]');
await page.click('[data-testid="scenario-load"]');
await page.waitForTimeout(4000);
await page.click('.evlog .row >> nth=10');
await page.waitForTimeout(800);
await page.screenshot({ path: `${out}/pvc-event.png` });
await page.click('[data-mode="ab"]');
await page.waitForTimeout(500);
await page.click('[data-testid="ab-run"]');
await page.waitForTimeout(12000);
await page.screenshot({ path: `${out}/ab.png` });
const m = await browser.newPage({ viewport: { width: 400, height: 860 }, deviceScaleFactor: 2 });
await m.goto("http://localhost:5180/");
await m.waitForTimeout(5000);
await m.screenshot({ path: `${out}/mobile.png` });
console.log(logs.join("\n"));
await browser.close();
